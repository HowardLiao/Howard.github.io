window.setLanguage = function(lang) {
    if (!window.TRANSLATIONS[lang]) lang = 'zh';
    window.currentLang = lang;
    localStorage.setItem('hl_lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-Hant' : (lang === 'ja' ? 'ja' : 'en');
    
    // Update active button state across desktop and mobile
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.dataset.lang === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
    
    const dict = window.TRANSLATIONS[lang];
    if (!dict) return;
    
    // Update data-i18n elements (textContent)
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });
    
    // Update data-i18n-html elements (innerHTML)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });
    
    // Update data-i18n-placeholder elements
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) {
            el.setAttribute('placeholder', dict[key]);
        }
    });
    
    // Special handling for title tag
    if (lang === 'en') {
        document.title = "Howard Liao, Ph.D. | VP of Tech / CIO / CISO / Forward-Deployed AI Architect";
    } else if (lang === 'ja') {
        document.title = "廖倫豪 博士 (Howard Liao, Ph.D.) | 技術副社長 兼 CIO / CISO / AI統括";
    } else {
        document.title = "廖倫豪 博士 (Howard Liao, Ph.D.) | 技術副總 暨 資訊長 (CIO) / 資安長 (CISO) / 前線 AI 架構師 戰略資歷檔案";
    }
    
    console.log('[i18n] Language switched to:', lang);
};

